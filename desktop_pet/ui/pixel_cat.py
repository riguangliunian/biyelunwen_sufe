def draw(painter: QPainter, cx: int, cy: int,
         state: str, frame: int,
         idle_action: str = 'none', jump_off: int = 0):
    bx = cx - _DISP_W // 2
    by = cy - _DISP_H + jump_off
    tw = int(math.sin(frame * (0.06 if state == 'sleeping' else 0.16))
             * (1 if state == 'sleeping' else 3))
    _sprite(painter, bx, by, tw)
    _blush(painter, bx, by, state)
    _eyes(painter, bx, by, state, frame, idle_action)
