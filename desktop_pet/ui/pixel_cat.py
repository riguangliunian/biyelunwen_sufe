# ── Eye overlay ───────────────────────────────────────────────────────────────

def _eyes(p: QPainter, bx: int, by: int,
          state: str, frame: int, idle_action: str):
    # Erase original eye pixels
    p.fillRect(bx + _EYE_X, by + _EYE_Y, _EYE_W, _EYE_H, _P12)

    lx, ly = bx + _LEC[0], by + _LEC[1]
    rx, ry = bx + _REC[0], by + _REC[1]

    def eye(cx, cy, k=_K):
        p.fillRect(cx - 2, cy - 2, 4, 4, k)

    def eye_line(cx, cy):
        p.fillRect(cx - 2, cy,     4, 2, _K)

    def eye_happy(cx, cy):
        p.fillRect(cx - 2, cy + 1, 2, 2, _K)
        p.fillRect(cx,     cy - 1, 2, 2, _K)
        p.fillRect(cx + 2, cy + 1, 2, 2, _K)

    def shine(cx, cy, side='right'):
        dx = cx + 1 if side == 'right' else cx - 3
        p.fillRect(dx, cy - 2, 2, 2, _W)

    def eye_eating(cx, cy):
        p.fillRect(cx - 2, cy,     2, 2, _K)
        p.fillRect(cx,     cy - 2, 2, 2, _K)
        p.fillRect(cx + 2, cy,     2, 2, _K)

    if state == 'sleeping':
        eye_line(lx, ly); eye_line(rx, ry)

    elif state == 'eating':
        if (frame // 3) % 2 == 0:
            eye_eating(lx, ly); eye_eating(rx, ry)
            _mouth_open(p, bx, by)
        else:
            eye_line(lx, ly); eye_line(rx, ry)

    elif state == 'happy':
        eye_happy(lx, ly); eye_happy(rx, ry)

    elif state == 'sleepy':
        eye(lx, ly); eye(rx, ry)
        p.fillRect(lx - 2, ly - 2, 4, 2, _P12)
        p.fillRect(rx - 2, ry - 2, 4, 2, _P12)

    elif state == 'hungry':
        eye(lx, ly); eye(rx, ry)
        p.fillRect(lx,     ly - 5, 4, 2, _K)
        p.fillRect(rx + 1, ry - 5, 2, 2, _K)

    elif state == 'working':
        p.fillRect(lx - 2, ly,     4, 2, _K)
        p.fillRect(lx - 1, ly - 2, 2, 4, _K)
        p.fillRect(rx - 2, ry,     4, 2, _K)
        p.fillRect(rx - 1, ry - 2, 2, 4, _K)

    elif idle_action == 'look_left':
        eye(lx, ly); eye(rx, ry)
        shine(lx, ly, 'left'); shine(rx, ry, 'left')

    elif idle_action == 'look_right':
        eye(lx, ly); eye(rx, ry)
        shine(lx, ly, 'right'); shine(rx, ry, 'right')

    elif idle_action == 'yawn':
        eye_line(lx, ly); eye_line(rx, ry)

    else:
        blink = 56 <= (frame % 60) <= 58
        if blink:
            eye_line(lx, ly); eye_line(rx, ry)
        else:
            eye(lx, ly); eye(rx, ry)
            shine(lx, ly); shine(rx, ry)


def _mouth_open(p: QPainter, bx: int, by: int):
    mx, my = bx + 20, by + 40
    p.fillRect(mx, my, 8, 5, _K)
    p.fillRect(mx + 1, my + 1, 6, 3, QColor(220, 100, 100))


# ── FX overlays ───────────────────────────────────────────────────────────────

def _fx(p: QPainter, bx: int, by: int, state: str, frame: int):
    if state == 'sleeping':
        zf = (frame // 7) % 10
        for i in range(min(zf + 1, 3)):
            alpha = max(0, 220 - (zf - i) * 55)
            p.setPen(QColor(160, 160, 255, alpha))
            p.setFont(QFont("Arial", 9 + i * 3, QFont.Weight.Bold))
            p.drawText(bx + 30 + i * 11, by + 28 - i * 12, "z")

    elif state == 'happy':
        for i, (dx, dy) in enumerate([(5, 8), (125, 12), (65, 4)]):
            if (frame + i * 5) % 14 < 7:
                p.setPen(QColor(255, 220, 60, 220))
                p.setFont(QFont("", 14))
                p.drawText(bx + dx, by + dy, "✦")

    elif state == 'working':
        dot_f = (frame // 4) % 3
        for i in range(3):
            if i <= dot_f:
                p.fillRect(bx + 18 + i * 5, by + 38, 4, 4,
                           QColor(255, 210, 50, 200))

    elif state == 'eating':
        for i in range(2):
            t = (frame + i * 20) % 40
            if t < 30:
                alpha = max(0, 200 - t * 5)
                p.setPen(QColor(240, 100, 120, alpha))
                p.setFont(QFont("", 10))
                p.drawText(bx + 8 + i * 14, by + 55 - t, "♡")
